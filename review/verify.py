"""Task 1: verify the Phase-1 review outputs from the detail CSV (not from the summary).
Read-only; writes review/VERIFY.md and review/verify_cells.json."""
import csv, json
from collections import Counter, defaultdict
from _lib import *
import optimization as opt

D = list(csv.DictReader(open('sensitivity_detail.csv')))
S = list(csv.DictReader(open('sensitivity_summary.csv')))
def key(r): return (r['profile'], int(r['size']))
win = defaultdict(dict)       # (profile,size) -> {variant: frozenset(winner ids)}
for r in D:
    v = (r['session'], r['approach'], r['normalisation'])
    win[key(r)][v] = frozenset(r['winner'].split('|'))
V_W = ('A', 'weighted', 'minmax'); V_SH = ('A', 'weighted', 'share'); V_B = ('B', 'weighted', 'minmax')
V_NS = ('A', 'weighted_without_scalability', 'minmax'); V_RS = ('A', 'rank_sum', 'minmax'); V_RT = ('A', 'runtime_only', 'minmax')
cells = sorted(win)
lab = lambda c: f'{c[0]} @ {c[1]:,}'
short = lambda s: ' | '.join(sorted(s))

chg_norm = [c for c in cells if win[c][V_W] != win[c][V_SH]]
chg_ses = [c for c in cells if win[c][V_W] != win[c][V_B]]
ns_app = [c for c in cells if V_NS in win[c]]
chg_ns = [c for c in ns_app if win[c][V_W] != win[c][V_NS]]
ties = [c for c in cells if len(win[c][V_W]) > 1]
d_rt = [c for c in cells if win[c][V_W] != win[c][V_RT]]
d_rs = [c for c in cells if win[c][V_W] != win[c][V_RS]]
# rule for "unchanged under all applicable checks"
stable = [c for c in cells if len(win[c][V_W]) == 1 and c not in chg_norm and c not in chg_ses and c not in chg_ns]
stable_incl_ties = [c for c in cells if c not in chg_norm and c not in chg_ses and c not in chg_ns]
# strict variant: also require rank-sum and runtime-only agree (not part of the 26 rule)
stable_strict = [c for c in stable if c not in d_rs]

L = []
P = L.append
P('# VERIFY: Phase-1 review outputs\n')
P('Generated by `review/verify.py` from `sensitivity_detail.csv` (255 rows), recomputed independently of `sensitivity_summary.csv`.\n')
P('## 1. The "26 of 45" figure\n')
P('**Rule used.** A profile-size cell counts as *unchanged under all applicable checks* when ALL of the following hold, using the session-A min-max weighted result as the reference:')
P('1. its weighted winner is **unique** (not a tied set);')
P('2. the winner (as a set) is the same under share-of-total normalisation;')
P('3. the winner is the same when scored on **session B** data (runtime, growth and k from session B; accuracy shared);')
P('4. *if* the profile has a scalability weight and another criterion remains, the winner is the same with scalability removed (min-max). Where the check cannot be run (no scalability weight, or scalability is the only criterion) it is **not applicable** and does not count against the cell.')
P('Tied sets are compared as sets. A tied cell is excluded by rule 1 (it has no unique winner). Rank-sum and runtime-only picks are *not* part of this rule (they are different methods, not perturbations of the weighted result).\n')
P(f'**Result: {len(stable)} of {len(cells)}.** Confirmed: {"YES (26)" if len(stable)==26 else "CORRECTED, number is %d" % len(stable)}.')
P(f'- Not unique winner: {len(ties)} cells. Cells with a unique winner: {len(cells)-len(ties)}.')
P(f'- Variant that ignores rule 1 (ties allowed to count as stable): {len(stable_incl_ties)}.')
P(f'- Stricter variant that also requires the rank-sum pick to equal the weighted pick: {len(stable_strict)}.')
P(f'- Overlap check: cells failing at least one perturbation = {len([c for c in cells if c in chg_norm or c in chg_ses or c in chg_ns])}; ties not already in that set = {len([c for c in ties if c not in chg_norm and c not in chg_ses and c not in chg_ns])}.\n')
P('Stable cells by profile:')
byp = Counter(c[0] for c in stable)
for p, _, _ in [(x[1], 0, 0) for x in opt.PROFILES]:
    P(f'- {p}: {byp.get(p,0)} of 5 (sizes {", ".join(f"{c[1]:,}" for c in stable if c[0]==p) or "none"})')

P('\n## 2. Counts in `sensitivity_summary.csv` vs the detail rows\n')
sm = {key(r): r for r in S}
checks = []
def add(name, from_detail, from_summary, expect=None):
    checks.append((name, from_detail, from_summary, expect, from_detail == from_summary and (expect is None or from_detail == expect)))
add('weighted differs from runtime-only', len(d_rt), sum(r['weighted_vs_runtime_only'] == 'differ' for r in S), 33)
add('weighted differs from rank-sum', len(d_rs), sum(r['weighted_vs_rank_sum'] == 'differ' for r in S), 13)
add('changes under share normalisation', len(chg_norm), sum(r['changes_under_share_normalisation'] == 'yes' for r in S), 4)
add('scalability removal: applicable cells', len(ns_app), sum(r['changes_without_scalability'] != 'not assessable' for r in S), 15)
add('scalability removal: changes (of applicable)', len(chg_ns), sum(r['changes_without_scalability'] == 'yes' for r in S), 7)
add('changes under session B', len(chg_ses), sum(r['changes_by_session'] == 'yes' for r in S), 7)
add('exact ties (weighted, min-max, A)', len(ties), sum(int(r['tied_set_size']) > 1 for r in S), 2)
P('| Count | From detail rows | From summary | Expected | Match |'); P('|---|---|---|---|---|')
for n, a, b, e, ok in checks: P(f'| {n} | {a} | {b} | {e} | {"match" if ok else "**MISMATCH**"} |')
rowmis = [c for c in cells if (sm[c]['weighted_pick'].split('|') and frozenset(sm[c]['weighted_pick'].split('|')) != win[c][V_W])]
P(f'\nPer-cell weighted pick: summary vs detail disagree in {len(rowmis)} cells.')
P(f'Detail row count by approach: {dict(Counter((r["session"], r["approach"], r["normalisation"]) for r in D))}')

P('\n## 3. Table 19 in full (session A, min-max, 50/50/50/0)\n')
pub = {100: ('nest/threads4', .244, 'nest/threads2', .254, 9, 6, 5), 500: ('snntorch/cpu', .277, 'spikingjelly/cpu', .322, 6, 4, 7),
       1000: ('snntorch/cpu', .255, 'spikingjelly/cpu', .283, 5, 7, 4), 5000: ('brian2/numpy', .044, 'brian2/cython', .045, 7, 7, 4),
       10000: ('brian2/cython', .000, 'brian2/numpy', .002, 15, None, 1)}
P('| N | Winner (score) | Runner-up (score) | Grid wins | Brian2/Cython grid wins | Pareto | Published | Result |'); P('|---|---|---|---|---|---|---|---|')
t19 = {}
for n in SIZES:
    r = opt.evaluate_four(n); w, ru = r['rows'][0], r['rows'][1]
    cy = next(x for x in r['rows'] if x['id'] == 'brian2/cython')['scenario_wins']
    pw, ps, pr, prs, pg, pc, pp = pub[n]
    ok = (w['id'] == pw and f"{w['score']:.3f}" == f'{ps:.3f}' and ru['id'] == pr and f"{ru['score']:.3f}" == f'{prs:.3f}'
          and w['scenario_wins'] == pg and (pc is None or cy == pc) and len(r['pareto']) == pp)
    t19[n] = dict(winner=w['id'], score=w['score'], runner_up=ru['id'], runner_up_score=ru['score'], grid_wins=w['scenario_wins'], cython_wins=cy, pareto=len(r['pareto']), pareto_ids=[x['id'] for x in r['pareto']])
    P(f"| {n:,} | {w['id']} ({w['score']:.4f}) | {ru['id']} ({ru['score']:.4f}) | {w['scenario_wins']}/15 | {cy} | {len(r['pareto'])} | {pw} {ps}, {pr} {prs}, wins {pg}, Cython {pc}, Pareto {pp} | {'match' if ok else '**MISMATCH**'} |")
P('\nNote: published 10,000 runner-up Brian2/NumPy 0.002 is the rounded 0.0019; published "Brian2/Cython: n" is not given for 10,000 (it is the winner, 15/15).')

P('\n## 4. Cells that change under each check\n')
exp = {
 'normalisation (share vs min-max)': (chg_norm, {('Balanced', 100), ('Accuracy + speed*', 100), ('Balanced', 5000), ('Speed + memory', 5000)}),
 'session B': (chg_ses, {('Fast SNN', 10000), ('Speed + memory', 500), ('Speed + memory', 1000), ('Accuracy + speed*', 100), ('Accuracy + speed*', 500), ('Accuracy + speed*', 1000), ('Accuracy + speed*', 5000)}),
 'removing scalability': (chg_ns, {('Scaling + accuracy*', n) for n in SIZES} | {('Memory + scaling', 100), ('Memory + scaling', 500)}),
 'exact ties': (ties, {('Low-memory SNN', 100), ('Low-memory SNN', 500)}),
}
flags = []
for name, (got, e) in exp.items():
    g = set(got)
    P(f'### {name}: {len(g)} cells; expected {len(e)}; **{"identical to expected" if g == e else "DIFFERENT"}**')
    for c in sorted(g, key=lambda x: (x[1], x[0])):
        extra = ''
        if name.startswith('normal'): extra = f' : min-max {short(win[c][V_W])} to share {short(win[c][V_SH])}'
        if name == 'session B': extra = f' : A {short(win[c][V_W])} to B {short(win[c][V_B])}'
        if name.startswith('removing'): extra = f' : with {short(win[c][V_W])} to without {short(win[c][V_NS])}'
        if name == 'exact ties': extra = f' : tied set {short(win[c][V_W])}'
        P(f'- {lab(c)}{extra}')
    if g != e:
        flags.append(name); P(f'- **Expected but absent:** {sorted(e-g)}; **present but unexpected:** {sorted(g-e)}')
    P('')
P('Exact ties in the expected list: Low-memory 100 all-tied (8 of 8): ' + str(len(win[("Low-memory SNN",100)][V_W]) == 8) + '; Low-memory 500 = snnTorch and Brian2/Cython: ' + str(win[("Low-memory SNN",500)][V_W] == {'snntorch/cpu', 'brian2/cython'}))
P('\nFlags (differences from expected lists): ' + (', '.join(flags) if flags else 'none'))
open('VERIFY.md', 'w').write('\n'.join(L) + '\n')
json.dump(dict(stable=[list(c) for c in stable], chg_norm=[list(c) for c in chg_norm], chg_ses=[list(c) for c in chg_ses],
               chg_ns=[list(c) for c in chg_ns], ns_applicable=[list(c) for c in ns_app], ties=[list(c) for c in ties],
               d_rt=len(d_rt), d_rs=len(d_rs), t19=t19), open('verify_cells.json', 'w'), indent=1)
print('\n'.join(L))
